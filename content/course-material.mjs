import { Chess } from 'chess.js';
export const start = new Chess().fen();
export function after(...moves) {
  const game = new Chess();
  moves.forEach((move) => game.move(move));
  return game.fen();
}
export function position(white, black, turn = 'w', rights = '-') {
  const game = new Chess();
  game.clear();
  for (const [pieces, color] of [
    [white, 'w'],
    [black, 'b'],
  ])
    for (const piece of pieces.split(' ').filter(Boolean))
      if (
        game.get(piece.slice(1)) ||
        !game.put({ type: piece[0].toLowerCase(), color }, piece.slice(1))
      )
        throw new Error(`Invalid piece: ${piece}`);
  return game
    .fen()
    .split(' ')
    .map((v, i) => (i === 1 ? turn : i === 2 ? rights : v))
    .join(' ');
}
const p = position;
export const s = (title, fen, body, question, targets, success) => ({
  title,
  fen,
  body,
  question,
  kind: 'squares',
  targets: targets.split(' '),
  success,
});
export const m = (title, fen, body, question, line, success, goal) => ({
  title,
  fen,
  body,
  question,
  kind: 'move',
  lines: [line.split(' ')],
  success,
  ...(goal ? { goal } : {}),
});
export const q = (title, fen, body, question, good, bad, other, success) => ({
  title,
  fen,
  body,
  question,
  kind: 'choice',
  options: [good, bad, other],
  success,
});
