export const positionalCourses = positionalProgram.map((t) =>
  c(
    t.id,
    t.title,
    t.track,
    t.outcome,
    t.examples.flatMap((e) => {
      const game = new Chess(e.fen);
      const sans = e.line.split(' ').map((uci) => {
        const move = game.move({
          from: uci.slice(0, 2),
          to: uci.slice(2, 4),
          ...(uci[4] ? { promotion: uci[4] } : {}),
        });
        return move.san;
      });
      const route = sans.join(' ');
      return [
        {
          ...m(
            `${e.title}: на доске`,
            e.fen,
            e.idea,
            `Воспроизведите пример ${route}. Затем проверьте, какую возможность он создаёт или какой риск показывает.`,
            e.line,
            e.idea,
          ),
          difficulty: 3,
          expanded: true,
          demo: e.line.split(' '),
          debrief: e.answer,
        },
        {
          ...q(
            `${e.title}: объяснить результат`,
            game.fen(),
            e.idea,
            `Какой вывод верен после показанного продолжения ${route}?`,
            e.answer,
            e.alternative,
            e.other,
            e.idea,
          ),
          difficulty: 2,
          expanded: true,
          debrief: `${t.outcome} Применяйте вывод к реальной позиции: изменение одной пешки или защитника может изменить оценку.`,
        },
      ];
    }),
  ),
);
