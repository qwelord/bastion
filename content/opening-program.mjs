function trace(san) {
  const game = new Chess();
  const positions = [game.fen()];
  const moves = san.split(' ').map((word) => {
    const move = game.move(word);
    positions.push(game.fen());
    return move.from + move.to + (move.promotion ?? '');
  });
  return { game, positions, moves };
}
